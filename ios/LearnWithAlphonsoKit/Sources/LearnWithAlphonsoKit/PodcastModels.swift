import Foundation

/// Podcast library models, Phase 1b (see docs/superpowers/specs/
/// 2026-09-24-podcast-phase1b-ios-design.md).
///
/// Mirrors the web app's `PodcastFolder` in src/lib/podcast-tree.ts and
/// `PodcastEpisode` in src/lib/podcast.functions.ts. Ported rather than
/// shared -- this repo has no TS/Swift sharing mechanism, same as the
/// SRS/hearts/progress-math ports.
public struct PodcastFolder: Sendable, Equatable, Identifiable {
    public let id: String
    public let parentID: String?
    public let slug: String
    public let title: String
    public let description: String?
    public let sortOrder: Int
    /// The root folder's course code (`en`, `fr`, `es`); nil means shown for every course.
    public let course: String?

    public init(
        id: String,
        parentID: String?,
        slug: String,
        title: String,
        description: String?,
        sortOrder: Int,
        course: String? = nil
    ) {
        self.id = id
        self.parentID = parentID
        self.slug = slug
        self.title = title
        self.description = description
        self.sortOrder = sortOrder
        self.course = course
    }
}

/// One published episode's id and folder: enough to prune empty folders and to sweep
/// downloads of episodes that have been unpublished, without fetching every folder.
public struct PodcastPublishedEpisodeRef: Equatable, Sendable {
    public let episodeID: String
    public let folderID: String

    public init(episodeID: String, folderID: String) {
        self.episodeID = episodeID
        self.folderID = folderID
    }
}

public struct PodcastEpisode: Sendable, Equatable, Identifiable {
    public let id: String
    public let folderID: String
    public let slug: String
    public let title: String
    public let description: String?
    public let audioURL: URL
    public let durationSeconds: Int
    /// Already clamped by PodcastPlayback.clampPosition when it came off
    /// the wire -- see PodcastClient.fetchEpisodes.
    public let positionSeconds: Int
    /// The `updated_at` of this user's playback row when it was read, or
    /// nil when no row exists yet.
    ///
    /// Carried so a later write can use optimistic concurrency: the client
    /// sends this value back and the write is rejected if the stored one
    /// has moved on. That is what distinguishes a *stale* device's flush
    /// from a deliberate rewind -- guarding on position magnitude would
    /// reject the rewind, and guarding on now() would accept the stale
    /// write, since now() is evaluated when the write lands.
    public let playbackUpdatedAt: String?
    /// Read by a synthetic voice (`source = 'tts'`); the Listen screens label it `PodcastLabel.aiNarrated`.
    public let aiNarrated: Bool
    /// The episode's own course code (`en`, `fr`, `es`), or nil when unset.
    public let course: String?

    public init(
        id: String,
        folderID: String,
        slug: String,
        title: String,
        description: String?,
        audioURL: URL,
        durationSeconds: Int,
        positionSeconds: Int,
        playbackUpdatedAt: String?,
        aiNarrated: Bool,
        course: String?
    ) {
        self.id = id
        self.folderID = folderID
        self.slug = slug
        self.title = title
        self.description = description
        self.audioURL = audioURL
        self.durationSeconds = durationSeconds
        self.positionSeconds = positionSeconds
        self.playbackUpdatedAt = playbackUpdatedAt
        self.aiNarrated = aiNarrated
        self.course = course
    }
}

/// The "AI-narrated" label, the same wording and rule as the web (`src/lib/podcast-label.ts`) and Android.
public enum PodcastLabel {
    public static let aiNarrated = "AI-narrated"

    /// Episodes generated by text-to-speech are AI-narrated; uploaded recordings are not labelled.
    public static func isAiNarrated(source: String?) -> Bool { source == "tts" }

    /// A downloaded episode's row subtitle in the offline list.
    public static func downloadedSubtitle(aiNarrated: Bool) -> String {
        (["Downloaded"] + (aiNarrated ? [Self.aiNarrated] : [])).joined(separator: " \u{00B7} ")
    }

    /// An episode row's subtitle on the Listen screen: length, then "Resume" and "AI-narrated" when they apply.
    public static func rowSubtitle(durationSeconds: Int, resume: Bool, aiNarrated: Bool) -> String {
        let length = String(format: "%d:%02d", durationSeconds / 60, durationSeconds % 60)
        return ([length] + (resume ? ["Resume"] : []) + (aiNarrated ? [Self.aiNarrated] : []))
            .joined(separator: " \u{00B7} ")
    }
}
