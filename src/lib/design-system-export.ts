export function parseIcon(name: string, svg: string): Icon {
  const title = /<title>([^<]*)<\/title>/.exec(svg)?.[1] ?? name;
  const elements: IconElement[] = [];
  for (const m of svg.matchAll(/<(path|rect|circle)\s([^>]*?)\/>/g)) {
    const attrs: Record<string, string> = {};
    for (const a of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    const role = attrs["data-role"] as IconElement["role"];
    delete attrs["data-role"];
    delete attrs.fill;
    delete attrs.stroke;
    elements.push(
      role
        ? { tag: m[1] as IconElement["tag"], attrs, role }
        : { tag: m[1] as IconElement["tag"], attrs },
    );
  }
  return { name, title, svg, elements };
}

export function loadDesignSource(root: string): DesignSource {
  const tokens = JSON.parse(fs.readFileSync(path.join(root, TOKENS_JSON), "utf8")) as DesignTokens;
  const dir = path.join(root, ICONS_DIR);
  const icons = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".svg"))
    .sort()
    .map((f) =>
      parseIcon(
        f.replace(/\.svg$/, ""),
        fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n"),
      ),
    );
  return { tokens, icons };
}

// ---------------------------------------------------------------- helpers

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const upperSnake = (s: string) => s.replace(/[A-Z]/g, (c) => `_${c}`).toUpperCase();
const n = (v: number) => String(+v.toFixed(4));
const f = (v: number) => `${n(v)}f`;
const variantNames = (src: DesignSource) => [
  ...src.icons.map((i) => ({ icon: i, solid: false, asset: `ds-${i.name}` })),
  ...src.tokens.icons.solid.map((s) => ({
    icon: src.icons.find((i) => i.name === s)!,
    solid: true,
    asset: `ds-${s}-solid`,
  })),
];
const camel = (asset: string) =>
  asset.replace(/^ds-/, "").replace(/-(\w)/g, (_, c: string) => c.toUpperCase());
const rgba = (hex: Hex, a: number) =>
  `rgba(${parseInt(hex.slice(1, 3), 16)}, ${parseInt(hex.slice(3, 5), 16)}, ${parseInt(hex.slice(5, 7), 16)}, ${n(a)})`;
const opszFor = (t: TypeRole) => (t.family === "display" ? (t.opsz ?? t.size) : undefined);

// ---------------------------------------------------------------- web

function cssBlock(selector: string, mode: Mode): string {
  return `${selector} {\n${Object.entries(mode)
    .map(([k, v]) => `  --c-${kebab(k)}: ${v};`)
    .join("\n")}\n}`;
}

function cssShadow(layers: ShadowLayer[], tint: Hex): string {
  return layers
    .map((l) => {
      const color = l.color === "line" ? "var(--c-line)" : rgba(tint, l.opacity);
      return `0 ${n(l.y)}px ${n(l.blur)}px ${n(l.spread)}px ${color}`;
    })
    .join(", ");
}

export function renderCss({ tokens: t }: DesignSource): string {
  const fontFace = (spec: FontSpec) => {
    const w = spec.axes.wght;
    const lines = [
      `  font-family: "${spec.name}";`,
      `  src: url("/fonts/${spec.web}") format("woff");`,
      `  font-weight: ${w[0]} ${w[1]};`,
    ];
    if (spec.axes.wdth) lines.push(`  font-stretch: ${spec.axes.wdth[0]}% ${spec.axes.wdth[1]}%;`);
    lines.push("  font-display: swap;");
    return `@font-face {\n${lines.join("\n")}\n}`;
  };
  const scale = [
    `  --ds-font-display: "${t.fonts.display.name}", "Avenir Next", "Segoe UI", system-ui, sans-serif;`,
    `  --ds-font-body: "${t.fonts.body.name}", "Avenir Next", "Segoe UI", system-ui, sans-serif;`,
    ...Object.entries(t.space).map(([k, v]) => `  --ds-space-${kebab(k)}: ${v}px;`),
    ...Object.entries(t.radius).map(
      ([k, v]) => `  --ds-radius-${k}: ${k === "pill" ? 9999 : v}px;`,
    ),
    ...Object.entries(t.edge).map(([k, v]) => `  --ds-edge-${kebab(k)}: ${v}px;`),
    ...(["resting", "floating", "sheet"] as const).map(
      (k) => `  --ds-shadow-${k}: ${cssShadow(t.elevation[k], t.elevation.shadowTint)};`,
    ),
    ...Object.entries(t.motion.duration).map(([k, v]) => `  --ds-duration-${kebab(k)}: ${v}ms;`),
    ...Object.entries(t.motion.easing).map(
      ([k, v]) => `  --ds-ease-${kebab(k)}: cubic-bezier(${v.map(n).join(", ")});`,
    ),
    ...Object.entries(t.league)
      .filter(([k]) => !k.startsWith("$"))
      .map(([k, v]) => `  --c-league-${k}: ${v};`),
  ];
  const typeClasses = Object.entries(t.type).map(([k, r]) => {
    const lines = [
      `  font-family: var(--ds-font-${r.family});`,
      `  font-weight: ${r.weight};`,
      `  font-size: ${r.size}px;`,
      `  line-height: ${r.lineHeight}px;`,
    ];
    if (r.width !== 100) lines.push(`  font-stretch: ${r.width}%;`);
    const opsz = opszFor(r);
    if (opsz !== undefined) lines.push(`  font-variation-settings: "opsz" ${opsz};`);
    if (r.tracking) lines.push(`  letter-spacing: ${n(r.tracking)}em;`);
    if (r.uppercase) lines.push("  text-transform: uppercase;");
    if (r.tnum) lines.push("  font-variant-numeric: tabular-nums;");
    return `.ds-type-${kebab(k)} {\n${lines.join("\n")}\n}`;
  });
  const themeInline = Object.keys(t.palettes.royal.light).map(
    (k) => `  --color-ds-${kebab(k)}: var(--c-${kebab(k)});`,
  );
  return `/* ${HEADER} */

/* The round-6 design system. Royal light is the default; the palette is set on <html> as data-palette and night as
   data-ds-mode. Screens read --c-* (or the bg-ds-* / text-ds-* utilities) and never a value. */

${fontFace(t.fonts.display)}

${fontFace(t.fonts.body)}

:root {
${scale.join("\n")}
}

${cssBlock(":root", t.palettes.royal.light)}

${cssBlock(':root[data-palette="meadow"]', t.palettes.meadow.light)}

${cssBlock(':root[data-ds-mode="night"]', t.palettes.royal.night)}

${cssBlock(':root[data-palette="meadow"][data-ds-mode="night"]', t.palettes.meadow.night)}

/* Lessons stay light in night mode (the rooms are lit paintings): a .ds-light screen keeps its palette's light values. */
.ds-light {
  color-scheme: light;
}

${cssBlock(':root[data-ds-mode="night"] .ds-light', t.palettes.royal.light)}

${cssBlock(':root[data-palette="meadow"][data-ds-mode="night"] .ds-light', t.palettes.meadow.light)}

@theme inline {
${themeInline.join("\n")}
}

${typeClasses.join("\n\n")}
`;
}

