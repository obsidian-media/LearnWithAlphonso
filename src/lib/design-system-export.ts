function standaloneSvg(icon: Icon, solid: boolean): string {
  const els = icon.elements
    .filter((e) => !(solid && e.role === "highlight"))
    .map((e) => {
      const paint =
        e.role === "dot" || solid
          ? 'fill="#000000" stroke="#000000"'
          : 'fill="none" stroke="#000000"';
      const attrs = Object.entries(e.attrs)
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      const stroke =
        e.role === "dot"
          ? 'stroke-width="0"'
          : 'stroke-width="2" stroke-linecap="round" stroke-linejoin="round"';
      return `  <${e.tag} ${attrs} ${paint} ${stroke}/>`;
    });
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">\n${els.join("\n")}\n</svg>\n`;
}

