/** Every generated file, keyed by its path from the repo root. */
export function renderAll(src: DesignSource): Record<string, string> {
  const out: Record<string, string> = {
    [WEB_CSS]: renderCss(src),
    [WEB_TOKENS_TS]: renderTokensTs(src),
    [WEB_ICONS_TS]: renderIconsTs(src),
    [SWIFT]: renderSwift(src),
    [KOTLIN]: renderKotlin(src),
    [`${IOS_ICON_FOLDER}/Contents.json`]: `${JSON.stringify({ info: { author: "xcode", version: 1 } }, null, 2)}\n`,
  };
  for (const v of variantNames(src)) {
    out[`${IOS_ICON_FOLDER}/${v.asset}.imageset/Contents.json`] = IMAGESET(v.asset);
    out[`${IOS_ICON_FOLDER}/${v.asset}.imageset/${v.asset}.svg`] = standaloneSvg(v.icon, v.solid);
    out[`${ANDROID_DRAWABLE_DIR}/${v.asset.replace(/-/g, "_")}.xml`] = renderVector(
      v.icon,
      v.solid,
    );
  }
  return out;
}

/** Runs prettier over the TypeScript outputs, so the generated files pass the repo's lint as written. */
export async function formatOutputs(
  outputs: Record<string, string>,
  root: string,
): Promise<Record<string, string>> {
  const prettier = await import("prettier");
  const out: Record<string, string> = {};
  for (const [rel, text] of Object.entries(outputs)) {
    if (!rel.endsWith(".ts")) {
      out[rel] = text;
      continue;
    }
    const filepath = path.join(root, rel);
    const options = (await prettier.resolveConfig(filepath)) ?? {};
    out[rel] = await prettier.format(text, { ...options, filepath });
  }
  return out;
}
