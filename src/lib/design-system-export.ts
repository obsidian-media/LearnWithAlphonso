export function toAndroidPathData(e: IconElement): string {
  const a = (k: string) => parseFloat(e.attrs[k] ?? "0");
  if (e.tag === "path") return e.attrs.d;
  if (e.tag === "circle") {
    const [cx, cy, r] = [a("cx"), a("cy"), a("r")];
    return `M${n(cx - r)},${n(cy)} A${n(r)},${n(r)} 0 1 0 ${n(cx + r)},${n(cy)} A${n(r)},${n(r)} 0 1 0 ${n(cx - r)},${n(cy)} Z`;
  }
  const [x, y, w, h, rx] = [a("x"), a("y"), a("width"), a("height"), a("rx")];
  const A = (ex: number, ey: number) => `A${n(rx)},${n(rx)} 0 0 1 ${n(ex)},${n(ey)}`;
  return [
    `M${n(x + rx)},${n(y)}`,
    `H${n(x + w - rx)}`,
    A(x + w, y + rx),
    `V${n(y + h - rx)}`,
    A(x + w - rx, y + h),
    `H${n(x + rx)}`,
    A(x, y + h - rx),
    `V${n(y + rx)}`,
    A(x + rx, y),
    "Z",
  ].join(" ");
}

function renderVector(icon: Icon, solid: boolean): string {
  const paths = icon.elements
    .filter((e) => !(solid && e.role === "highlight"))
    .map((e) => {
      const filled = e.role === "dot" || solid;
      const stroke =
        e.role === "dot"
          ? ""
          : `\n        android:strokeColor="#FF000000"\n        android:strokeWidth="2"\n        android:strokeLineCap="round"\n        android:strokeLineJoin="round"`;
      return `    <path\n        android:pathData="${toAndroidPathData(e)}"\n        android:fillColor="${filled ? "#FF000000" : "#00000000"}"${stroke} />`;
    });
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- ${HEADER} -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${paths.join("\n")}
</vector>
`;
}

