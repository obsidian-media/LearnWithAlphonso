// Wrong options (and, where more than one answer would fit, a short English clue) for the
// hand-authored French and Spanish A1/A2 fill-in packs. See romance-options.ts for why.
//
// Each pack is a list aligned with the pack's data lines. An entry is "wrong1,wrong2,wrong3" with an
// optional " ~clue": the clue is added to the sentence in brackets, the way the Spanish packs already
// write "(excited)". An empty entry keeps the engine's old behaviour (the other answers of the pack),
// which is right for the packs that conjugate one verb and for the possessive drills.
//
// How a wrong option earns its place (docs/distractor-policy.md, rule 3): the rest of the sentence
// rules it out (gender, number, a missing elision, the wrong verb form) or the clue does. Where two
// words really fit, the clue says which one is meant.
//
// Answers, ids and order are untouched. Lines a native speaker should still read are listed in the
// PR body.

export type ClozeOptions = { wrong: string[]; hint?: string };

function parse(rows: string[]): Record<number, ClozeOptions> {
  const out: Record<number, ClozeOptions> = {};
  rows.forEach((row, i) => {
    if (!row.trim()) return;
    const [options, hint] = row.split("~").map((s) => s.trim());
    out[i] = { wrong: options!.split(",").map((s) => s.trim()), ...(hint ? { hint } : {}) };
  });
  return out;
}

