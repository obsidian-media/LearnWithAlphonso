/**
 * Writes src/data/unit-rooms.ts: every unit's room, made by the spec's rule (src/lib/room-plan.ts). Run it once
 * after a room's art lands (remove the room from PENDING_ROOMS first), or after units are added, then re-export
 * the native bundles: bun scripts/export-ios-content.ts and bun scripts/export-android-content.ts.
 *
 * Hand overrides: put them in OVERRIDES below so a rerun keeps them. src/lib/unit-rooms.test.ts still checks that
 * every unit has a room with art and that no two neighbours share one.
 *
 * Usage: bun scripts/gen-unit-rooms.ts
 */
import fs from "node:fs";
import path from "node:path";
import { getCourse, type Course } from "../src/data/courses";
import { planUnitRooms, roomsWithArt } from "../src/lib/room-plan";

/** unitId -> roomId, applied to both the room in use and the plan. */
const OVERRIDES: Record<string, string> = {};

const room: Record<string, string> = {};
const planned: Record<string, string> = {};
const painted = new Set(roomsWithArt());
const summary: string[] = [];
for (const course of ["en", "es", "fr"] as Course[]) {
  const plan = planUnitRooms(
    getCourse(course).curriculum.map((u) => ({ id: u.id, level: u.level, title: u.title })),
    painted,
  );
  for (const p of plan) {
    room[p.id] = OVERRIDES[p.id] ?? p.room;
    planned[p.id] = OVERRIDES[p.id] ?? p.planned;
  }
  summary.push(`${course} ${plan.length}`);
}

const table = (o: Record<string, string>) =>
  Object.entries(o)
    .map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`)
    .join("\n");

const out = `// Generated by scripts/gen-unit-rooms.ts (the room plan in src/lib/room-plan.ts). Hand overrides go in that
// script's OVERRIDES so a rerun keeps them. Checked by src/lib/unit-rooms.test.ts.

/** The room each unit uses today: its planned room if painted, otherwise a painted fallback. unitId -> roomId. */
export const UNIT_ROOMS: Record<string, string> = {
${table(room)}
};

/** The room the spec plans for each unit, once every room is painted (see PENDING_ROOMS in rooms.ts). */
export const UNIT_ROOMS_PLANNED: Record<string, string> = {
${table(planned)}
};
`;
const target = path.resolve(import.meta.dirname, "../src/data/unit-rooms.ts");
const prettier = await import("prettier");
const options = (await prettier.resolveConfig(target)) ?? {};
fs.writeFileSync(target, await prettier.format(out, { ...options, filepath: target }));
console.log(`wrote ${Object.keys(room).length} unit rooms (${summary.join(", ")})`);
