// scripts/build-grader-wordlists.ts
/**
 * Builds the per-language "is this a real word?" lists the written-answer grader uses (see
 * src/data/grader-words/README.md for the source and licence).
 *
 *   bun scripts/build-grader-wordlists.ts <dir holding en_50k.txt, fr_50k.txt, es_50k.txt>
 *
 * Input: the FrequencyWords 2018 "50k" lists (`word count` per line, OpenSubtitles-derived, CC-BY-SA-4.0).
 * Filters, in this order:
 *   1. letters only (no digits, apostrophes or hyphens), lower case, at least 5 letters (the grader only treats a
 *      word of 5+ letters as a typo candidate, so shorter words never need to be looked up);
 *   2. a count of at least MIN_COUNT, which drops the long tail where a subtitle corpus keeps its frequent
 *      misspellings (recieve 125, definately 135, thier 127, beleive 140, wich 265, seperate 166);
 *   3. a word that is clearly another language's word (its share of that corpus is more than FOREIGN_RATIO times its
 *      share of this one) is dropped, because the Spanish and French subtitle lists carry English dialogue.
 * Output: src/data/grader-words/<lang>.ts and its byte-identical Deno copy in supabase/functions/_shared/grader-words/.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const LANGS = ["en", "fr", "es"] as const;
const MIN_COUNT = 400;
const FOREIGN_RATIO = 5;
const MIN_LETTERS = 5;

const dir = process.argv[2];
if (!dir) throw new Error("usage: bun scripts/build-grader-wordlists.ts <dir with en_50k.txt ...>");

const counts: Record<string, Map<string, number>> = {};
const totals: Record<string, number> = {};
for (const lang of LANGS) {
  const map = new Map<string, number>();
  let total = 0;
  for (const line of readFileSync(join(dir, `${lang}_50k.txt`), "utf8").split(/\r?\n/)) {
    const [word, n] = line.trim().split(" ");
    if (!word || !n) continue;
    map.set(word.toLowerCase(), (map.get(word.toLowerCase()) ?? 0) + Number(n));
    total += Number(n);
  }
  counts[lang] = map;
  totals[lang] = total;
}

const share = (lang: string, word: string) => (counts[lang]!.get(word) ?? 0) / totals[lang]!;

for (const lang of LANGS) {
  const kept: string[] = [];
  for (const [word, n] of counts[lang]!) {
    if (!/^\p{L}+$/u.test(word) || [...word].length < MIN_LETTERS || n < MIN_COUNT) continue;
    const mine = share(lang, word);
    if (LANGS.some((other) => other !== lang && share(other, word) > FOREIGN_RATIO * mine))
      continue;
    kept.push(word);
  }
  kept.sort();
  const body =
    `// Generated by scripts/build-grader-wordlists.ts. Do not edit by hand; see src/data/grader-words/README.md.\n` +
    `// ${lang}: ${kept.length} words of 5+ letters, space separated.\n` +
    `export default ${JSON.stringify(kept.join(" "))};\n`;
  for (const out of [
    join("src", "data", "grader-words"),
    join("supabase", "functions", "_shared", "grader-words"),
  ]) {
    mkdirSync(out, { recursive: true });
    writeFileSync(join(out, `${lang}.ts`), body);
  }
  console.log(lang, kept.length);
}
