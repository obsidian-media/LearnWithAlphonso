  IT: { rects: bands(["#009246", "#FFFFFF", "#CE2B37"], "v") },
  IE: { rects: bands(["#169B62", "#FFFFFF", "#FF883E"], "v") },
  BE: { rects: bands(["#000000", "#FDDA24", "#EF3340"], "v") },
  RO: { rects: bands(["#002B7F", "#FCD116", "#CE1126"], "v") },
  PE: { rects: bands(["#D91023", "#FFFFFF", "#D91023"], "v", [1, 2, 1]) },
